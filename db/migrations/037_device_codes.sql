-- 037 — Device authorization codes (V3 local-first, L3)
--
-- WHAT THIS IS. The `device_codes` table backs the OAuth-style device flow that
-- links a LOCAL DeeWaanAI install to a hosted marketplace account: the local app
-- shows a short `user_code`, the signed-in user approves it on the hosted site,
-- and the local install exchanges the single-use `device_code` for a long-lived
-- token. Codes expire in 10 minutes and are never reused.
--
-- ADDITIVE ONLY. One new table; nothing existing is touched.
--
-- NOTE: this file follows the repo's numbered-SQL convention (009..036 live
-- outside drizzle-kit's journal, which only tracks the squashed 0000 baseline).
-- The matching SQLite migration is db/migrations-sqlite/0001_device_codes.sql,
-- generated by drizzle-kit from the regenerated db/schema.sqlite.ts mirror.

CREATE TABLE `device_codes` (
	`id` int AUTO_INCREMENT NOT NULL,
	`device_code` varchar(64) NOT NULL,
	`user_code` varchar(12) NOT NULL,
	`user_id` int,
	`status` enum('pending','approved','denied') NOT NULL DEFAULT 'pending',
	`expires_at` timestamp NOT NULL,
	`created_at` timestamp NOT NULL DEFAULT (now()),
	CONSTRAINT `device_codes_id` PRIMARY KEY(`id`),
	CONSTRAINT `uq_device_codes_device_code` UNIQUE(`device_code`),
	CONSTRAINT `uq_device_codes_user_code` UNIQUE(`user_code`),
	CONSTRAINT `device_codes_user_id_users_id_fk` FOREIGN KEY (`user_id`) REFERENCES `users`(`id`) ON DELETE cascade ON UPDATE no action
);
