// Decision D12 (OFFERING-REDESIGN-TECH-SPECS §1.1): a benchmark may always run
// as a PRIVATE evaluation with whatever panel the owner can afford, but a
// result becomes publishable EVIDENCE only under a vendor-disjoint panel —
// 3 judging models from 3 different model DEVELOPERS, each pair running the 3
// prompt variants as a cross product (9 ratings per output), with no judge
// sharing a developer with ANY model that generated an output in the plan
// (the thesis's disjointness rule D33). "Vendor" is resolved from the
// admin-reviewed catalog's `vendor` column (migration 031), never from
// `llm_providers`: one hosting key serves many vendors' models.
//
// This module is the single source of the refusal text so the create/quote
// gate and the publication re-check cannot drift apart. An unknown vendor is
// DISJOINT FROM NOTHING: it can never fill a panel slot, and it never
// collides with another model either.
//
// The ICC helpers here are the reliability statistic D12 asks the descriptive
// summary to report: two-way mixed analysis of variance, absolute agreement,
// single measures (ICC(3,1)) and average measures (ICC(3,k), the panel mean —
// ICC(3,9) for a full D12 panel). Degenerate designs return NULL with the
// condition named, never a fabricated number.

import {
  JUDGE_PROMPT_VARIANTS, panelVariants,
  type CandidateSpec, type JudgePromptVariant, type JudgeSpec, type SnapshotStep,
} from "./benchmarkTypes";
import { resolveModelVendors } from "../modelCatalogService";

/**
 * D12: an evidence-grade panel is exactly this shape — three judges, each under a
 * different frozen prompt variant, every generating model from a different
 * developer than any judge.
 *
 * WHERE THESE NUMBERS COME FROM, because a reader must not "simplify" them:
 *  - Three judges, drawn from different model families, is the Panel-of-LLM-
 *    evaluators result: Verga et al. 2024, "Replacing judges with juries"
 *    (arXiv:2404.18796) — a diverse panel tracked human judgement better than a
 *    single large judge, for less. The COUNT is theirs, not a statistic's.
 *  - Judges must not share a developer with anything that GENERATED an output
 *    under review: that is self-enhancement bias, Zheng et al. 2023
 *    (MT-Bench/Chatbot Arena, arXiv:2306.05685).
 *  - ICC(3,1)/ICC(3,k) below is Shrout & Fleiss 1979 — it describes how the
 *    agreement statistic is computed GIVEN three raters. It does not justify
 *    three raters, and citing it as the reason would be a mistake.
 *
 * Vendor vs family: the paper says families; this checks `vendor` (the model's
 * developer, from the reviewed catalog). For closed models the two coincide, and
 * where they diverge this is STRICTER than the paper — it would refuse a
 * same-developer, different-family judge. Deliberate: an unknown or uncatalogued
 * model is treated as disjoint from nothing, so it can never fill a panel slot.
 */
export const EVIDENCE_PANEL_JUDGES = 3;
export const EVIDENCE_PANEL_VARIANTS = JUDGE_PROMPT_VARIANTS.length;
export const EVIDENCE_PANEL_RATINGS_PER_OUTPUT = EVIDENCE_PANEL_JUDGES * EVIDENCE_PANEL_VARIANTS;

export interface GeneratorModel {
  /** Human-readable origin, e.g. `candidate "x" step 2`. */
  label: string;
  /** Null when the plan names no model for it (solo baselines and unmodelled
   *  steps resolve to a project default only at run time) — disjointness
   *  against an unnameable generator cannot be verified, so it refuses. */
  model: string | null;
}

/** The plan's WHOLE generator set (D33): every model that can produce an
 *  output this panel will grade. An imported output is user-reported
 *  provenance, not generated by this plan (§4.1/A01), so it contributes none. */
export function generatorModelsOfPlan(
  candidates: Array<Pick<CandidateSpec, "stableCandidateId" | "strategy" | "overrideModel">>,
  steps: SnapshotStep[],
): GeneratorModel[] {
  const out: GeneratorModel[] = [];
  for (const c of candidates) {
    if (c.strategy === "imported_output") continue;
    if (c.strategy === "solo_baseline") {
      out.push({ label: `candidate "${c.stableCandidateId}" (solo baseline)`, model: null });
      continue;
    }
    if (c.overrideModel) {
      out.push({ label: `candidate "${c.stableCandidateId}"`, model: c.overrideModel });
      continue;
    }
    for (const s of steps) out.push({ label: `candidate "${c.stableCandidateId}" step ${s.stepOrder}`, model: s.model });
  }
  // Dedupe: one refusal per offending MODEL (the label of the first
  // occurrence is shown), and per unattributed candidate slot. A workflow
  // that runs the same model on five steps must not repeat itself five times.
  const seen = new Set<string>();
  return out.filter((g) => {
    const key = g.model !== null ? `model:${g.model}` : `label:${g.label}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

export interface PanelAssessment {
  /** False means: private evaluation allowed, publication as evidence refused. */
  evidenceGrade: boolean;
  /** Full refusal sentences, each led by a plain reason code. Empty iff evidenceGrade. */
  issues: string[];
  vendorByModel: Record<string, string | null>;
  judges: number;
  /** Distinct prompt variants the panel declares (1 for every pre-D12 plan). */
  variants: number;
  /** Distinct resolved judge vendors; unknown vendors are excluded, never guessed. */
  judgeVendors: string[];
}

/** Pure core of the gate: callers resolve vendors from the catalog first
 *  (async), then hand the map in so this logic stays unit-testable without a
 *  database. */
export function evaluateEvidencePanel(opts: {
  judges: JudgeSpec[];
  generators: GeneratorModel[];
  vendors: Record<string, string | null>;
}): PanelAssessment {
  const issues: string[] = [];
  const J = opts.judges.length;
  const declared = [...new Set(opts.judges.map((j) => j.variant))].filter((v): v is JudgePromptVariant => v !== undefined);
  const vendorOf = (model: string): string | null => opts.vendors[model] ?? null;

  if (J !== EVIDENCE_PANEL_JUDGES) {
    issues.push(`panel_needs_three_judges: an evidence-grade panel has exactly ${EVIDENCE_PANEL_JUDGES} judging models; this plan names ${J}. Add judges from two more model developers, or keep this benchmark private — a private evaluation may run any panel, but its results cannot be published as evidence.`);
  }
  if (declared.length !== EVIDENCE_PANEL_VARIANTS) {
    issues.push(`panel_needs_three_variants: each of the ${EVIDENCE_PANEL_JUDGES} judges must declare a different prompt variant so every output is rated ${EVIDENCE_PANEL_RATINGS_PER_OUTPUT} times (${EVIDENCE_PANEL_JUDGES} judges × ${EVIDENCE_PANEL_VARIANTS} prompts); this panel declares ${declared.length} variant(s)${declared.length ? ` (${declared.join(", ")})` : ""}. Set a different variant from ${JUDGE_PROMPT_VARIANTS.join(" | ")} on each judge.`);
  }

  const knownJudges: Array<{ judge: JudgeSpec; vendor: string }> = [];
  for (const judge of opts.judges) {
    const vendor = vendorOf(judge.model);
    if (!vendor) {
      issues.push(`panel_vendor_unknown: judge model ${judge.model} has no model developer (vendor) recorded in the reviewed catalog — an unknown vendor counts as disjoint from nothing, so it can never fill an evidence-grade panel slot (it also never collides with another model). Ask an admin to record its vendor in the catalog, or choose a catalogued model.`);
      continue;
    }
    knownJudges.push({ judge, vendor });
  }
  // Judge-vs-judge collisions, among KNOWN vendors only: two unknowns never
  // collide (unknown attributes nothing, including a collision).
  for (let a = 0; a < knownJudges.length; a++) {
    for (let b = a + 1; b < knownJudges.length; b++) {
      if (knownJudges[a].vendor === knownJudges[b].vendor) {
        issues.push(`panel_shared_vendor: judges ${knownJudges[a].judge.model} and ${knownJudges[b].judge.model} are both built by ${knownJudges[a].vendor} — an evidence-grade panel needs ${EVIDENCE_PANEL_JUDGES} different model developers, not three keys from one. Replace one judge with a model from another developer (the developer is read from the reviewed catalog, never from which hosting provider's key served the call).`);
      }
    }
  }
  // Judge-vs-generator (D33): checked against the WHOLE generator set.
  for (const gen of opts.generators) {
    if (gen.model === null) {
      issues.push(`panel_generator_model_unattributed: ${gen.label} runs with no model named in the plan (a project default answers at run time), so its developer cannot be checked against the panel. Name every generating model, or keep this evaluation private.`);
      continue;
    }
    const gv = vendorOf(gen.model);
    if (!gv) {
      issues.push(`panel_generator_vendor_unknown: generating model ${gen.model} has no model developer (vendor) recorded in the reviewed catalog — vendor disjointness cannot be verified against it, so no panel can be proven independent of it. Catalogue its developer or replace it.`);
      continue;
    }
    for (const { judge, vendor } of knownJudges) {
      if (vendor === gv) {
        issues.push(`panel_judge_generator_vendor_overlap: judge ${judge.model} is built by ${vendor}, the same developer as generating model ${gen.model} (${gen.label}) — no judge may share a developer with anything that generated an output in this plan. Replace the judge or that generator before this result can become evidence.`);
      }
    }
  }

  const judgeVendors = [...new Set(knownJudges.map((k) => k.vendor))];
  return {
    evidenceGrade: issues.length === 0,
    issues,
    vendorByModel: opts.vendors,
    judges: J,
    variants: panelVariants(opts.judges).length,
    judgeVendors,
  };
}

/** The one call sites use: resolve developers from the reviewed catalog, then
 *  run the pure gate. Used at draft creation (when a listing is attached), at
 *  quote/approve/start (blocking there), and again at publication. Accepts a
 *  DRAFT plan too — drafts have no materialized `baseVersionId` yet, and the
 *  gate needs nothing but the panel and the candidate shapes. */
export async function assessBenchmarkPanel(
  plan: {
    judges: JudgeSpec[];
    candidates: Array<Pick<CandidateSpec, "stableCandidateId" | "strategy" | "overrideModel">>;
  },
  steps: SnapshotStep[],
): Promise<PanelAssessment> {
  const generators = generatorModelsOfPlan(plan.candidates, steps);
  const models = [
    ...plan.judges.map((j) => j.model),
    ...generators.map((g) => g.model).filter((m): m is string => !!m),
  ];
  const vendors = await resolveModelVendors(models);
  return evaluateEvidencePanel({ judges: plan.judges, generators, vendors });
}

// ─── ICC(3,1) / ICC(3,k) — two-way mixed, absolute agreement ─────────
// The k = 3 here is the panel mandated above (Verga et al. 2024); this section
// only computes the reliability statistic, per Shrout & Fleiss 1979.
//
// Matrix convention: ROWS = cases (each distinct rating target: one executed
// candidate output graded by the full panel), COLUMNS = judges (a column per
// judge slot × prompt-variant pair — 9 columns for a full D12 panel).
// McGraw & Wong (1996) / Shrout & Fleiss (1979) decomposition:
//   MSR = k·Σ(rowMean−grand)² / (n−1)            (cases)
//   MSC = n·Σ(colMean−grand)² / (k−1)            (judges)
//   MSres = Σ(x−rowMean−colMean+grand)² / ((n−1)(k−1))  (case×judge residual)
//   ICC(3,1) = (MSR−MSres) / (MSR + (k−1)·MSres + (k/n)·(MSC−MSres))
//   ICC(3,k) = (MSR−MSres) / (MSR + (MSC−MSres)/n)
// The (k−1) is not a citation detail: expanding the variance components
// σ²α=(MSR−MSres)/k, σ²β=(MSC−MSres)/n, σ²e=MSres into ICC(3,1)=σ²α/(σ²α+σ²β+σ²e)
// and multiplying through by k lands on exactly this closed form, and writing
// `k·MSres` instead understates the statistic (0.894199 against 0.922631 on the
// 5×3 matrix in judgePanel.test.ts).
// Only COMPLETE rows are used — a case missing any rater is dropped rather
// than mean-filled, and the count of usable rows is reported with the result.

export interface IccResult {
  icc31: number | null;
  icc3k: number | null;
  /** Non-null when the design is degenerate: exactly why no number is reported. */
  nullReason: string | null;
  usedRows: number;
  columns: number;
}

const round6 = (x: number): number => Number(x.toFixed(6));

/** Design-level degeneracy the ICC must refuse to compute through, checked
 *  BEFORE the matrix (decision D12 names these outright): fewer than 3
 *  judges, and a panel that is not multi-vendor — including one whose vendor
 *  attribution is missing, which cannot be SHOWN independent. Returns the
 *  reason, or null when the design is sound enough to hand to `computeIcc`. */
export function iccDesignNull(judgeVendors: Array<string | null>, judgeCount: number): string | null {
  if (judgeCount < EVIDENCE_PANEL_JUDGES) {
    return `the panel has ${judgeCount} judging model(s); ICC(3,·) presumes the 3-judge design, fewer than 3 judges is degenerate`;
  }
  const unknown = judgeVendors.filter((v) => v === null).length;
  if (unknown > 0) {
    return `${unknown} of ${judgeVendors.length} judge model(s) have no developer (vendor) recorded in the reviewed catalog, so vendor independence cannot be established`;
  }
  if (new Set(judgeVendors).size === 1) {
    return `every judge is a ${judgeVendors[0]} model: a single-vendor panel is a degenerate design for ICC(3,·)`;
  }
  return null;
}

export function computeIcc(matrix: number[][]): IccResult {
  const columns = matrix.length ? matrix[0].length : 0;
  const rows = matrix.filter((r) => r.length === columns && r.every(Number.isFinite));
  const n = rows.length;
  const base = { usedRows: n, columns };
  if (columns < 2) return { ...base, icc31: null, icc3k: null, nullReason: `the panel provides ${columns} rating column(s); ICC needs at least 2 judges` };
  if (n < 2) return { ...base, icc31: null, icc3k: null, nullReason: `fewer than 2 cases carry a complete panel (only ${n} do)` };

  const k = columns;
  const grand = rows.flat().reduce((a, x) => a + x, 0) / (n * k);
  const rowMeans = rows.map((r) => r.reduce((a, x) => a + x, 0) / k);
  const colMeans = Array.from({ length: k }, (_, j) => rows.reduce((a, r) => a + r[j], 0) / n);
  const msr = k * rowMeans.reduce((a, m) => a + (m - grand) ** 2, 0) / (n - 1);
  const msc = n * colMeans.reduce((a, m) => a + (m - grand) ** 2, 0) / (k - 1);
  let ssres = 0;
  rows.forEach((r, i) => { for (let j = 0; j < k; j++) ssres += (r[j] - rowMeans[i] - colMeans[j] + grand) ** 2; });
  const msres = ssres / ((n - 1) * (k - 1));

  if (msr === 0 && msc === 0 && msres === 0) {
    return { ...base, icc31: null, icc3k: null, nullReason: "every rating in the matrix is identical (there is no variance to be reliable about)" };
  }
  const denom31 = msr + (k - 1) * msres + (k / n) * (msc - msres);
  const denom3k = msr + (msc - msres) / n;
  if (!Number.isFinite(denom31) || !Number.isFinite(denom3k) || denom31 <= 0 || denom3k <= 0) {
    return { ...base, icc31: null, icc3k: null, nullReason: "the variance decomposition is degenerate for this matrix (non-positive denominator); ICC is undefined and no number is invented" };
  }
  return { ...base, icc31: round6((msr - msres) / denom31), icc3k: round6((msr - msres) / denom3k), nullReason: null };
}
